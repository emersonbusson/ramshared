//! Windows-specific dynamic library loader (using Win32 APIs).
//!
//! Covered requirements: RF-4, DT-5.

use core::ffi::{c_char, c_int, c_void};
use std::ffi::CStr;
use windows_sys::Win32::Foundation::{FreeLibrary, GetLastError, HMODULE};
use windows_sys::Win32::System::LibraryLoader::{GetProcAddress, LoadLibraryW};

/// Opens the specified dynamic library (converts CStr to UTF-16).
///
/// # Safety
/// The `filename` pointer must point to a valid null-terminated C-string.
pub unsafe fn open(filename: *const c_char) -> *mut c_void {
    let cstr = unsafe { CStr::from_ptr(filename) };
    let string_str = match cstr.to_str() {
        Ok(s) => s,
        Err(_) => return core::ptr::null_mut(),
    };

    // Convert to null-terminated UTF-16 wide string
    let wide: Vec<u16> = string_str.encode_utf16().chain(Some(0)).collect();

    let handle = unsafe { LoadLibraryW(wide.as_ptr()) };
    if handle.is_null() {
        return core::ptr::null_mut();
    }
    handle
}

/// Loads the specified symbol from the library.
///
/// # Safety
/// `handle` must be a valid pointer returned by `open`.
/// `symbol` must point to a valid null-terminated C-string.
pub unsafe fn sym(handle: *mut c_void, symbol: *const c_char) -> *mut c_void {
    if handle.is_null() {
        return core::ptr::null_mut();
    }
    // GetProcAddress returns Option<unsafe extern "system" fn() -> isize> in windows-sys 0.61.
    let addr = unsafe { GetProcAddress(handle as HMODULE, symbol as *const u8) };
    match addr {
        Some(f) => f as *mut c_void,
        None => core::ptr::null_mut(),
    }
}

/// Closes the dynamic library.
///
/// # Safety
/// `handle` must be a valid pointer returned by `open` that has not been closed yet.
pub unsafe fn close(handle: *mut c_void) -> c_int {
    if handle.is_null() {
        return 0;
    }
    let ok = unsafe { FreeLibrary(handle as HMODULE) };
    if ok != 0 {
        0 // Returns 0 for success, matching dlclose behavior
    } else {
        -1 // Failure
    }
}

/// Returns the last error message generated by the loader using GetLastError().
pub fn error() -> String {
    let code = unsafe { GetLastError() };
    format!("Windows error code: 0x{code:08X}")
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used)]

    use super::*;
    use windows_sys::Win32::Foundation::SetLastError;

    #[test]
    fn test_error_formatting() {
        unsafe { SetLastError(0x00000005) };
        assert_eq!(error(), "Windows error code: 0x00000005");

        unsafe { SetLastError(0xC0000005) };
        assert_eq!(error(), "Windows error code: 0xC0000005");

        unsafe { SetLastError(0) };
        assert_eq!(error(), "Windows error code: 0x00000000");
    }

    #[test]
    fn test_invalid_library_handling() {
        use std::fs;
        use std::ffi::CString;

        let dummy_path = "test_invalid_format_12345.dll";
        // Create a dummy file with invalid PE data to test loader failure handling.
        fs::write(dummy_path, b"invalid pe data").unwrap();

        let c_path = CString::new(dummy_path).unwrap();

        // SAFETY: c_path is a valid null-terminated string pointing to the dummy file.
        let handle = unsafe { open(c_path.as_ptr()) };
        assert!(handle.is_null(), "Loading an invalid library format should return a null pointer");

        let err_msg = error();
        assert!(!err_msg.is_empty(), "Error message should not be empty");

        // Clean up safely
        if fs::metadata(dummy_path).is_ok() {
            let _ = fs::remove_file(dummy_path);
        }
    }

    #[test]
    fn test_missing_symbol_handling() {
        use std::ffi::CString;

        // Use a universally present system library on Windows to ensure consistent test execution.
        let valid_lib = CString::new("kernel32.dll").unwrap();

        // SAFETY: valid_lib is a valid null-terminated string pointing to a known system library.
        let handle = unsafe { open(valid_lib.as_ptr()) };
        assert!(!handle.is_null(), "kernel32.dll should load successfully on Windows/Wine");

        let missing_symbol = CString::new("ThisSymbolDoesNotExistInKernel32").unwrap();

        // SAFETY: handle is valid and missing_symbol is a valid null-terminated string.
        let sym_ptr = unsafe { sym(handle, missing_symbol.as_ptr()) };
        assert!(sym_ptr.is_null(), "Loading a nonexistent symbol should return a null pointer");

        // SAFETY: handle was opened successfully and has not been closed yet.
        let close_result = unsafe { close(handle) };
        assert_eq!(close_result, 0, "Closing the valid library should succeed");
    }
}
